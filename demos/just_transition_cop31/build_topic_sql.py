"""
Write queries/03_topic_flags.sql: the just transition Topic and its sub-topics, everywhere.

The base is the just transition Topic (Q47 classifier output). Topics are hierarchical, so
every passage tagged with a sub-topic (social protection, decent work, ...) is also tagged
Q47 and counts as just transition content. A passage tagged Q47 with none of the six
sub-topics got there only through the root's own labels ("just transition", "leave no one
behind", ...) or label-only descendants: that is the generic mention.

One query, returned as rows with a `section` column:
  year    corpus x publication year, 2012-2025: all passages and Q47 passages   -> chart 1
  corpus  per corpus and all, 2020-2025: Q47 passages, their sub-topic groups,
          and co-occurring energy Topics                                        -> chart 4
  ndc3    one row per country with an NDC 3.0: does any passage carry each
          sub-topic (and the two keyword searches inside the tree)?             -> chart 3
  region  World Bank region x corpus, national documents, 2020-2025            -> chart 6

Laws and policies tagged only with the Nature domain are left out everywhere.
"""

from pathlib import Path

import keyword_sql as kw

HERE = Path(__file__).resolve().parent

SUB = {
    "socprot": "Q53",
    "inclusion": "Q58",
    "legal": "Q1744",  # protection / inclusion
    "decent": "Q68",
    "skills": "Q1754",
    "greenjobs": "Q69",
}  # work
ENERGY = {
    "fossil": "Q638",
    "coal": "Q661",
    "supplymit": "Q2420",
    "renew": "Q567",
    "electrif": "Q2419",
    "grid": "Q2421",
    "storage": "Q287",
    "esector": "Q762",
}
OTHER = {"informal": "Q757"}
KEYWORD = {
    "dialogue": kw.predicate("social_dialogue"),
    "transition_workers": kw.predicate("transition_workers"),
}


def has(q: str) -> str:
    return f"array_contains('{q}'::variant, p.concept_ids)"


work = " or ".join(has(SUB[k]) for k in ("decent", "skills", "greenjobs"))
protect = " or ".join(has(SUB[k]) for k in ("socprot", "inclusion", "legal"))
# Three exclusive groups for chart 6: work / social protection / social inclusion & safeguards
# (legal safeguards sits with social inclusion under justice-informed governance, Q1733).
g_work = f"iff({work}, 1, 0)"
g_prot = f"iff({has(SUB['socprot'])}, 1, 0)"
g_incl = f"iff({has(SUB['inclusion'])} or {has(SUB['legal'])}, 1, 0)"
n_groups = f"({g_work} + {g_prot} + {g_incl})"
flag_cols = ",\n         ".join(
    ["iff(" + has("Q47") + ", 1, 0) as jt"]
    + [f"iff({has(q)}, 1, 0) as {k}" for k, q in {**SUB, **ENERGY, **OTHER}.items()]
    # keyword searches only on Q47 passages: these concepts sit inside the tree
    + [
        f"case when {has('Q47')} and {pred} then 1 else 0 end as {k}"
        for k, pred in KEYWORD.items()
    ]
    + [
        f"iff(({work}) and not ({protect}), 1, 0) as g_work",
        f"iff(({protect}) and not ({work}), 1, 0) as g_protect",
        f"iff(({work}) and ({protect}), 1, 0) as g_both",
        f"iff({has('Q47')} and not ({work}) and not ({protect}), 1, 0) as g_generic",
        f"{g_work} as any_work",
        f"iff({n_groups} = 1 and {g_work} = 1, 1, 0) as c_work",
        f"iff({n_groups} = 1 and {g_prot} = 1, 1, 0) as c_protect",
        f"iff({n_groups} = 1 and {g_incl} = 1, 1, 0) as c_include",
        f"iff({n_groups} >= 2, 1, 0) as c_multiple",
        "iff("
        + " or ".join(
            has(ENERGY[k])
            for k in ("fossil", "supplymit", "electrif", "grid", "storage", "esector")
        )
        + ", 1, 0) as any_energy",
    ]
)
FLAGS = (
    ["jt"]
    + list(SUB)
    + list(ENERGY)
    + list(OTHER)
    + list(KEYWORD)
    + ["g_work", "g_protect", "g_both", "g_generic", "any_energy"]
    + ["any_work", "c_work", "c_protect", "c_include", "c_multiple"]
)
# Co-occurrence counts are only wanted inside the Topic, so sum them on Q47 passages.
jt_sums = ", ".join(
    ["sum(jt) as jt"] + [f"sum(iff(jt = 1, {f}, 0)) as {f}" for f in FLAGS if f != "jt"]
)
maxes = ", ".join(f"max({f}) as {f}" for f in FLAGS)

sql = f"""-- Just transition Topic (Q47) and its sub-topics. Generated by build_topic_sql.py; do not edit.
-- WHAT YOU GET: rows with a `section` (year / corpus / ndc3 / region); see the script docstring.
-- Unit: passages (paragraphs and list items, >= 20 characters) in published documents with
-- classifier output. UNFCCC submissions by Parties only, without inventories. Laws and policies tagged
-- only with the Nature domain are left out. Co-occurrence columns count Q47 passages only.
with unfccc as (  -- UNFCCC submissions by Parties (incl. negotiating groups): the principal
                  -- carries author_type 'Party'; documents inherit it through principal_id
  select distinct d.id
  from PRODUCTION.PUBLISHED.DOCUMENTS d
  join PRODUCTION.PUBLISHED.DOCUMENTS pr on pr.id = d.principal_id,
       lateral flatten(input => d.labels) l, lateral flatten(input => pr.labels) a
  where d.category = 'UN submission' and l.value:id::string = 'un_convention::UNFCCC'
    and a.value:id::string = 'author_type::Party'
),
docs as (
  select d.id, year(d.published_date) as yr,
         case d.category when 'UN submission' then 'UNFCCC submissions'
                         when 'Policy' then 'Policies'
                         when 'Law' then 'Laws'
                         when 'Multilateral Climate Fund project' then 'Climate fund projects'
                         when 'Litigation' then 'Court documents' end as corpus,
         iff(d.entity_type = 'Nationally Determined Contribution (NDC)' and year(d.published_date) >= 2025, 1, 0) as ndc3,
         iff(array_size(d.regions) = 1 and d.category in ('Law', 'Policy', 'UN submission'),
             replace(d.regions[0]::string, 'East Asia and Pacific', 'East Asia & Pacific'), null) as region
  from PRODUCTION.PUBLISHED.DOCUMENTS d
  where not d.is_principal and not d.is_collection and d.document_status = 'published'
    and d.concept_ids is not null
    and d.category in ('UN submission', 'Policy', 'Law', 'Multilateral Climate Fund project', 'Litigation')
    and (d.category not in ('Law', 'Policy') or array_contains('Climate'::variant, d.domains))
    and (d.category <> 'UN submission'
         or (d.id in (select id from unfccc)
             and coalesce(d.entity_type, '') <> 'National Inventory Report (NIR)'
             and not (d.title ilike '%inventory%' or d.title ilike '%common reporting table%' or d.title like '%CRT%')))
),
ndc_country as (
  select d.id, replace(g.value::string, 'country::', '') as iso
  from PRODUCTION.PUBLISHED.DOCUMENTS d, lateral flatten(input => d.geographies) g
  where d.entity_type = 'Nationally Determined Contribution (NDC)' and year(d.published_date) >= 2025
    and g.value::string like 'country::%'
),
f as (
  select dc.id as doc_id, dc.yr, dc.corpus, dc.ndc3, dc.region,
         {flag_cols}
  from docs dc
  join PRODUCTION.PUBLISHED.PASSAGES p on p.document_id = dc.id
  where p.content_type in ('Text', 'List') and length(p.content) >= 20
)
select 'year' as section, corpus as grp, yr, count(*) as passages, {jt_sums}
from f where yr between 2012 and 2025 group by corpus, yr
union all
select 'corpus', coalesce(corpus, 'All'), null, count(*), {jt_sums}
from f where yr between 2020 and 2025 group by grouping sets ((corpus), ())
union all
select 'ndc3', n.iso, null, count(*), {maxes}
from f join ndc_country n on n.id = f.doc_id where f.ndc3 = 1 group by n.iso
union all
select 'region', region || ' / ' || corpus, null, count(*), {jt_sums}
from f where region is not null and yr between 2020 and 2025 group by region, corpus
"""

out = HERE / "queries" / "03_topic_flags.sql"
out.write_text(sql, encoding="utf-8")
print(f"wrote {out.name}: {len(sql):,} characters; flags: {FLAGS}")
